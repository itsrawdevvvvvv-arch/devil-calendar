// Release signing is driven by environment variables supplied by CI
// (KEYSTORE_BASE64 / KEY_ALIAS / KEYSTORE_PASSWORD / KEY_PASSWORD) or by a
// local keystore.properties file. When neither is present the release build
// stays unsigned so `assembleDebug` and PR builds never depend on secrets.
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}
fun secret(key: String): String? =
    (System.getenv(key) ?: keystoreProps.getProperty(key))?.takeIf { it.isNotBlank() }

val releaseStoreFile = secret("KEYSTORE_FILE")
val hasReleaseSigning = secret("KEYSTORE_BASE64") != null || releaseStoreFile != null

